-- 툭(Tuk) 초기 스키마 baseline.
--
-- 지금까지 Hibernate `ddl-auto: update` 가 만들어 온 스키마를 그대로 옮긴 것이다.
-- (운영 DB 는 이 파일로 처음부터 생성되고, 이미 테이블이 있는 개발 DB 는
--  `flyway.baseline-on-migrate: true` 로 이 버전을 건너뛴다)
--
-- 이후 스키마 변경은 엔티티만 고치지 말고 반드시 V2, V3... 마이그레이션을 추가할 것.
-- `ddl-auto` 는 validate 라서, 엔티티와 DB 가 어긋나면 기동 시점에 실패한다.

CREATE TABLE users (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    timestamp(6),
    updated_at    timestamp(6),
    nickname      varchar(30)  NOT NULL,
    profile_image varchar(255),
    provider      varchar(20)  NOT NULL,
    provider_id   varchar(255) NOT NULL,
    invite_code   varchar(16),
    CONSTRAINT uq_user_provider UNIQUE (provider, provider_id)
);

-- 방향(requester/addressee)은 수락 권한 판단용으로 보존하고,
-- 유일성은 정규화 쌍(min/max)에 건다 — (requester,addressee) 유니크는 A→B·B→A 중복을 허용하기 때문.
CREATE TABLE friendships (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   timestamp(6),
    updated_at   timestamp(6),
    status       varchar(20) NOT NULL,
    requester_id bigint      NOT NULL,
    addressee_id bigint      NOT NULL,
    user_low_id  bigint      NOT NULL,
    user_high_id bigint      NOT NULL,
    CONSTRAINT uq_friend_pair UNIQUE (user_low_id, user_high_id),
    CONSTRAINT ck_friendship_status CHECK (status IN ('PENDING', 'ACCEPTED')),
    CONSTRAINT fk_friendship_requester FOREIGN KEY (requester_id) REFERENCES users (id),
    CONSTRAINT fk_friendship_addressee FOREIGN KEY (addressee_id) REFERENCES users (id)
);

CREATE TABLE flashes (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   timestamp(6),
    updated_at   timestamp(6),
    sender_id    bigint       NOT NULL,
    activity     varchar(20)  NOT NULL,
    message      varchar(200),
    scheduled_at timestamp(6),
    expires_at   timestamp(6) NOT NULL,
    status       varchar(20)  NOT NULL,
    CONSTRAINT ck_flash_activity CHECK (activity IN ('MEAL', 'DRINK', 'CAFE', 'WALK', 'MOVIE', 'KARAOKE', 'ANYTHING')),
    CONSTRAINT ck_flash_status CHECK (status IN ('ACTIVE', 'EXPIRED', 'CLOSED')),
    CONSTRAINT fk_flash_sender FOREIGN KEY (sender_id) REFERENCES users (id)
);

-- status 는 PENDING/JOINED 만. DECLINED 는 설계 원칙상 절대 추가하지 않는다("거절 안 보임").
-- UNIQUE(flash_id, user_id) 가 멱등 합류를 보장한다.
CREATE TABLE flash_recipients (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6),
    updated_at timestamp(6),
    flash_id   bigint      NOT NULL,
    user_id    bigint      NOT NULL,
    status     varchar(20) NOT NULL,
    joined_at  timestamp(6),
    CONSTRAINT uq_flash_user UNIQUE (flash_id, user_id),
    CONSTRAINT ck_recipient_status CHECK (status IN ('PENDING', 'JOINED')),
    CONSTRAINT fk_recipient_flash FOREIGN KEY (flash_id) REFERENCES flashes (id),
    CONSTRAINT fk_recipient_user FOREIGN KEY (user_id) REFERENCES users (id)
);

-- Flash 와 1:1 (flash_id UNIQUE). place_set_by = 마지막으로 장소를 정한 멤버.
CREATE TABLE meetup_rooms (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   timestamp(6),
    updated_at   timestamp(6),
    flash_id     bigint       NOT NULL,
    place_name   varchar(255),
    place_lat    double precision,
    place_lng    double precision,
    place_set_by bigint,
    status       varchar(20)  NOT NULL,
    expires_at   timestamp(6) NOT NULL,
    CONSTRAINT uq_meetup_room_flash UNIQUE (flash_id),
    CONSTRAINT ck_room_status CHECK (status IN ('OPEN', 'CLOSED')),
    CONSTRAINT fk_room_flash FOREIGN KEY (flash_id) REFERENCES flashes (id),
    CONSTRAINT fk_room_place_set_by FOREIGN KEY (place_set_by) REFERENCES users (id)
);

CREATE TABLE device_tokens (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6),
    updated_at timestamp(6),
    user_id    bigint       NOT NULL,
    token      varchar(255) NOT NULL,
    platform   varchar(10)  NOT NULL,
    CONSTRAINT uq_device_token UNIQUE (token),
    CONSTRAINT ck_device_platform CHECK (platform IN ('IOS', 'ANDROID')),
    CONSTRAINT fk_device_token_user FOREIGN KEY (user_id) REFERENCES users (id)
);
